CREATE TABLE usuarios (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(100) NOT NULL,
    email VARCHAR2(100) UNIQUE NOT NULL,
    senha_hash VARCHAR2(255) NOT NULL,
    role VARCHAR2(20) DEFAULT 'USER' NOT NULL,
    criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE contas (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id NUMBER NOT NULL,
    numero_conta VARCHAR2(20) UNIQUE NOT NULL,
    saldo NUMBER(19,4) DEFAULT 0.0000 NOT NULL,
    status VARCHAR2(20) DEFAULT 'ATIVA',
    version NUMBER DEFAULT 0, 
    CONSTRAINT fk_usuario_conta FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
    CONSTRAINT chk_saldo_positivo CHECK (saldo >= 0)
);